"""Run a byte-identical wall generator only in an owned QA sandbox and compare actual shipped bytes."""
from pathlib import Path
import sys, subprocess, hashlib, json, datetime
qa=Path(__file__).resolve().parent;root=qa.parents[2]
stamp=datetime.datetime.now(datetime.timezone.utc).isoformat().replace('+00:00','Z')
run=qa/'runs'/(stamp.replace(':','-').replace('.','-')+'-wall-rebuild');project=run/'project'
project.resolve().relative_to((qa/'runs').resolve())
(project/'scripts').mkdir(parents=True);(project/'src/scene').mkdir(parents=True)
source=root/'mobile/scripts/generate-walls.py';before=source.read_bytes();target=project/'scripts/generate-walls.py';target.write_bytes(before)
result=subprocess.run([sys.executable,str(target)],cwd=project,text=True,capture_output=True,timeout=120)
(run/'output.log').write_text(result.stdout+result.stderr)
hashof=lambda b:hashlib.sha256(b).hexdigest()
checks=[]
for generated in sorted((project/'assets/materials').glob('*.png')):
    actual=root/'mobile/assets/materials'/generated.name
    checks.append({'file':generated.name,'generatedSha256':hashof(generated.read_bytes()),'actualSha256':hashof(actual.read_bytes()),'match':generated.read_bytes()==actual.read_bytes()})
report={'at':stamp,'commandExitCode':result.returncode,'sourceSha256':hashof(before),'sourceStable':source.read_bytes()==before,'mapCount':len(checks),'mismatches':[c for c in checks if not c['match']],'checks':checks,'scope':'Reproducibility in isolated QA copy; generator uses calibrated(-dx,+dy,1) PNG convention. No production assets regenerated by QA and no native-device claim.'}
(run/'result.json').write_text(json.dumps(report,indent=2));print(json.dumps({**report,'checks':None,'artifact':str(run/'result.json')}))
raise SystemExit(0 if result.returncode==0 and report['sourceStable'] and len(checks)==27 and not report['mismatches'] else 1)
